        let keys: Vec<String> = ["a", "a\0", "a\0x", "aa", "b", "z"]
            .into_iter()
            .map(String::from)
            .collect();
        for key in &keys {
            // Two fields under each key exercise the whole-child boundary rule.
            ctx.__set_u64(&path.push_element(key).push_interned(0), 1);
            ctx.__set_u64(&path.push_element(key).push_interned(1), 2);
        }
