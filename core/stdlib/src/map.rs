//! Secondary-index infrastructure for [`StorageMap`](crate::StorageMap) — the one
//! `Map<K, V>`. When the value carries `#[index]` fields the map gains
//! framework-maintained secondary indexes, so filtered reads are prefix scans of a
//! declared index rather than a `keys()` scan-and-filter. A value with no `#[index]`
//! (or a primitive value) is a plain map: [`Indexed::HAS_INDEXES`] is `false` and all
//! of this const-folds out — there is no separate map type.
//!
//! Layout (all ordinary path-prefixed `contract_state` rows, so versioned,
//! reorg-safe, and folded into the checkpoint hash):
//! ```text
//!   <primary>/<key>                              -> V
//!   <primary>#idx/<index_name>/<index_key>/<member> -> () | projection
//! ```
//! A `<member>` is the primary key (unsorted) or a `(sort, pk)` tuple (sorted). A
//! plain index leaf is void (`()`); a COVERING index (`#[index(include = …)]`) stores
//! the covered fields' concatenated codec elements AS the leaf value, so a
//! `.values()`/`.iter()` read returns them without a per-member point read (see
//! [`IndexEntry::projection`] and the covering query types).
//!
//! `index_name(key)` scans `<primary>#idx/<name>/<key>/`, whose child
//! segments ARE the primary keys. A key's index memberships are derived from its
//! value via [`Indexed`] — there is no separate record of them, so the value
//! stays the one source of truth (same as every other generated model). On
//! update the prior entries are recomputed and diffed against the new ones via
//! [`apply_index_diff`]: delete `old − new`, write `new − old`, so an unchanged
//! index (or a no-op re-set) costs zero index ops.
//!
//! Storage-deposit cost: each index entry is an ordinary write (one `contract_state`
//! row), so it carries its own storage deposit (the row's path + value bytes × D) just
//! like the value row — there is no unmetered side channel. A value with N `#[index]`
//! fields therefore counts the value's deposit plus one per live index entry toward its
//! setter's storage-deposit floor; a hot, frequently-rewritten indexed field is the
//! costliest shape. This is intentional (index rows are real, collateralized state),
//! but authors should expect indexed maps to cost proportionally more deposit than
//! plain ones.
//!
//! COVERING (`include = …`) sharpens both edges: the leaf value is no longer empty, so
//! the covered fields' bytes add to that row's deposit (a void leaf is priced on its
//! path alone), AND any change to a covered field rewrites the leaf in place — a write.
//! So covering pays off for COLD / rarely-mutated projections read often through the
//! index (the point: skip a per-member point read), and is a poor trade for a HOT
//! field that churns the leaf on every update while inflating its deposit. Prefer
//! covering immutable-after-create or slowly-changing fields; leave hot fields to a
//! plain index + per-key `get`.
//!
//! The type a contract declares is the inert [`StorageMap`] placeholder; the real
//! per-key `get`/`set`/`remove`/index accessors are generated by the
//! `#[derive(Model)]` field model. The only logic carried here is (a)
//! [`apply_index_diff`], the single audited maintenance routine both the field model
//! and the bulk [`Store`] impl call, and (b) the [`Store`] impl below, which keeps a
//! *wholesale* write of the map (root init, or any nested struct set through
//! `Store`) index-consistent — the field model's per-key path can't catch that.

