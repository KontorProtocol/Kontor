/// The codec element a value contributes as one index-bucket segment. The SINGLE
/// source every index path encodes through — a value's [`Indexed::index_entries`],
/// the read model's `__index_entries`, the in-place indexed-field setter, and the
/// generated typed index lookup — so the bucket a write lands in and the
/// bucket a lookup scans can never drift.
///
/// A bucket is an equality partition (order *within* it is irrelevant), so the
/// only requirement is a *distinct* element per value — no ordering, unlike a
/// [`KeyElement`] sort key. A [`KeyElement`] type encodes itself (a `u64` bucket
/// is a compact int element; a `Vec<u8>` its raw bytes — no hex). A storage enum
/// keys by its DISCRIMINANT (case name) as a string element, not its payload — so
/// `Failed(r)` always lands in the `"failed"` bucket and changing the payload is a
/// no-op for the index. The `Storage` derive supplies that impl (and a payload-free
/// `<E>Kind` marker for referencing a case without constructing one).
pub trait IndexKey {
    /// One complete, self-delimiting codec element (e.g. from [`KeyElement::encode`]).
    fn index_key(&self) -> Vec<u8>;
}

// A `KeyElement` type buckets by encoding itself — distinct per value, and far
// more compact than its `Display` for ints/bytes (a `u64` is ≤9 bytes vs up to 20
// decimal chars; `Vec<u8>` is raw, not 2× hex). No blanket `impl<T: KeyElement>`:
// it would collide with the discriminant impl the `Storage` derive emits for enums.
macro_rules! index_key_via_keyelement {
    ($($t:ty),*) => {
        $(
            impl IndexKey for $t {
                fn index_key(&self) -> Vec<u8> {
                    KeyElement::encode(self)
                }
            }
        )*
    };
}
index_key_via_keyelement!(bool, u8, u16, u32, u64, i8, i16, i32, i64, String, Vec<u8>);

/// An `Option<T>` indexes by its `none`/`some` **discriminant** (like an enum keys
/// by its case), ignoring the payload — so a composite index can partition on "is
/// this field set?" without a predicate DSL. The discriminant is a string element,
/// matching [`Presence`] (the payload-free marker a typed index lookup passes) and
/// storage enums, so the bucket a write lands in and a lookup scans agree. Blanket
/// over all `T`: `Option` is neither a keyed primitive nor a storage enum, so no
/// impl overlaps it.
impl<T> IndexKey for Option<T> {
    fn index_key(&self) -> Vec<u8> {
        let s = match self {
            None => "none",
            Some(_) => "some",
        };
        String::from(s).encode()
    }
}

/// The payload-free marker for bucketing an `Option` index field by presence —
/// the `Option` analogue of a storage enum's `<E>Kind`. Lets a lookup name the
/// bucket (`eligible(true, Presence::Absent)`) without constructing an
/// `Option` value or writing `None::<T>` with a turbofish. Its [`IndexKey`]
/// matches `Option`'s, so lookup and stored bucket can't drift.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Presence {
    Absent,
    Present,
}

impl IndexKey for Presence {
    fn index_key(&self) -> Vec<u8> {
        let s = match self {
            Presence::Absent => "none",
            Presence::Present => "some",
        };
        String::from(s).encode()
    }
}

/// One secondary-index membership of a value: which index, which bucket, and
/// (optionally) where it sorts within that bucket. The leaf it maps to is
/// `<index>/<bucket…>/<sort‖pk>` (see the `Map` module docs).
///
/// `bucket` is a vec so a composite index can partition on several fields (one
/// segment each, in declared order); a single-field index has one — each a
/// pre-encoded [`IndexKey`] codec element (distinct partitioning, order
/// irrelevant). `sort` is the sort field's pre-encoded codec element
/// (`KeyElement::encode`), which leads the `(sort, pk)` member tuple so the bucket
/// scans in value order. (A covering projection will be added here later as the
/// leaf *value*; the diff already keys on the leaf path so that stays additive.)
pub struct IndexEntry {
    /// The index's interned id (its declaration order within the value type), the
    /// structural `<index>` segment — a dict-ref, like every other structural name.
    /// Per value type; only ever used under that value's `#idx` root, so distinct
    /// value types' id spaces never meet.
    pub name_id: u8,
    pub bucket: Vec<Vec<u8>>,
    pub sort: Option<Vec<u8>>,
    /// The covering projection stored AS the leaf value: the `include=` fields'
    /// order-preserving codec elements, tuple-packed (`None` = a plain void leaf).
    /// It is NOT part of leaf identity (`same_leaf` ignores it) — a member whose
    /// covered value changed keeps the same leaf path, so the diff rewrites the value
    /// in place rather than moving the row.
    pub projection: Option<Vec<u8>>,
}

impl IndexEntry {
    /// The bucket-prefix path `<index>/<bucket…>` (where the count lives; members
    /// are its children). The index name is an interned structural segment; each
    /// bucket segment is a pre-encoded `IndexKey` element.
    fn bucket_path(&self, index_root: &KeyPath) -> KeyPath {
        index_root
            .push_interned(self.name_id)
            .push_raw_elements(&self.bucket)
    }

    /// The member element: the `(sort, pk)` nested tuple (so the bucket sorts by
    /// value, then key), or just the primary-key element when unsorted. `key` is
    /// the already-encoded primary-key element. Both inputs are full codec
    /// elements, so packing them is a tuple wrap.
    fn member_element(&self, key: &[u8]) -> Vec<u8> {
        match &self.sort {
            Some(sort) => keycodec::tuple_from_elements(&[sort, key]),
            None => key.to_vec(),
        }
    }

    /// Two entries share a leaf (same `<index>/<bucket…>/<member>`) iff they agree
    /// on name+bucket+sort. The diff keys on this; a future covering projection is
    /// the leaf *value*, updated in place when the path matches.
    fn same_leaf(&self, other: &IndexEntry) -> bool {
        self.name_id == other.name_id && self.bucket == other.bucket && self.sort == other.sort
    }
}

/// A value's secondary-index memberships. An empty result means "in no index" —
/// partial indexes fall out by omitting an entry when a predicate is false.
///
/// Every storage value implements this — structs/enums via `#[derive(Storage)]`,
/// primitives via the blanket-ish impls below — so one `Map<K, V>` covers both
/// plain and indexed values. `HAS_INDEXES` is a compile-time flag: the generated
/// `set`/`remove` skip all index maintenance when it's `false`, so a non-indexed
/// map compiles to exactly the plain path (verified: no read-before-write emitted).
pub trait Indexed {
    /// Whether this value declares any secondary indexes. Const so callers can
    /// `if <V as Indexed>::HAS_INDEXES { … }` and have the branch const-fold.
    const HAS_INDEXES: bool = false;
    fn index_entries(&self) -> Vec<IndexEntry> {
        Vec::new()
    }
}

// Primitive (leaf) storage values are never indexed. (WIT "primitives" like
// `Integer`/`Decimal`/`Holder` provide `Indexed` in built-in-types; these are the
// bare Rust types.)
macro_rules! impl_indexed_leaf {
    ($($t:ty),* $(,)?) => { $( impl Indexed for $t {} )* };
}
impl_indexed_leaf!(u8, u16, u32, u64, i32, i64, bool, String, Vec<u8>, ());

/// Reconcile one key's index rows from `old` to `new`: delete entries in `old`
/// that aren't in `new`, write entries in `new` that weren't in `old`. Unchanged
/// entries are left untouched (zero ops). Index roots are siblings of the
/// primary map.
///
/// `key` is the primary key's already-encoded codec element. Type-erased (raw
/// bytes, not generic `K`) so this stays the one audited routine every caller —
/// of differing key types — funnels through; the typed call sites encode. Because
/// every segment is now a self-delimiting codec element, a key may contain any
/// content (no delimiter to alias on — what the old `.`-join had to reject).
///
/// The caller computes `old`/`new`: the field model's `set`/`remove` load the
/// prior value and read its `Indexed::index_entries`; an in-place indexed-field
/// setter diffs just that field's entry; the bulk [`Store`] impl starts from
/// empty (a fresh wholesale write). Either way the maintenance logic lives only
/// here.
pub fn apply_index_diff<S: WriteStorage + ReadStorage + ?Sized>(
    ctx: &Rc<S>,
    index_root: &KeyPath,
    key: &[u8],
    old: &[IndexEntry],
    new: &[IndexEntry],
) {
    for entry in old {
        if !new.iter().any(|n| n.same_leaf(entry)) {
            let bucket = entry.bucket_path(index_root);
            // Decrement ONLY when the delete actually removed a live row.
            // `__delete` returns false for a no-op (the entry was already
            // tombstoned or never written — an index/count that drifted); counting
            // that as a removal would underflow the bucket count and trap. The
            // delete result is the authority on whether membership changed.
            if ctx.__delete(&bucket.push_raw_element(&entry.member_element(key))) {
                bump_bucket_count(ctx, &bucket, false);
            }
        }
    }
    for entry in new {
        if !old.iter().any(|o| o.same_leaf(entry)) {
            let bucket = entry.bucket_path(index_root);
            write_leaf(
                ctx,
                &bucket.push_raw_element(&entry.member_element(key)),
                entry,
            );
            bump_bucket_count(ctx, &bucket, true);
        }
    }
    // Covering only: a member whose LEAF (name+bucket+sort) is unchanged but whose
    // COVERED value changed keeps the same row — rewrite the leaf value in place, no
    // membership/count change. (`same_leaf` deliberately excludes the projection, so
    // this case is invisible to the delete/add passes above.)
    for entry in new {
        if let Some(prev) = old.iter().find(|o| o.same_leaf(entry))
            && prev.projection != entry.projection
        {
            let leaf = entry
                .bucket_path(index_root)
                .push_raw_element(&entry.member_element(key));
            write_leaf(ctx, &leaf, entry);
        }
    }
}

/// Write an index member's leaf: the covering projection as the value when present,
/// else a void (unit) leaf — the two shapes an index row can take.
fn write_leaf<S: WriteStorage + ?Sized>(ctx: &Rc<S>, leaf: &[u8], entry: &IndexEntry) {
    match &entry.projection {
        Some(projection) => ctx.__set_list_u8(leaf, projection.clone()),
        None => ctx.__set_void(leaf),
    }
}

/// Adjust a bucket's framework-maintained member count. The count lives AT the
/// bucket-prefix path (`<map>#idx/<name>/<key>`); the bucket's members are its
/// CHILDREN (`…/<key>/<primary_key>`), so this value is invisible to the
/// index child-scan and to `keys()`. Maintained only here — the one site
/// every index add/remove funnels through (field-model `set`/`remove`, in-place
/// setter, and the bulk `Store`) — so it can't drift from the membership it
/// counts. It's an ordinary height-versioned `contract_state` row, so it rolls
/// back with everything else on a reorg.
fn bump_bucket_count<S: WriteStorage + ReadStorage + ?Sized>(
    ctx: &Rc<S>,
    bucket: &KeyPath,
    up: bool,
) {
    let current = ctx.__get_u64(bucket).unwrap_or(0);
    // A decrement always follows a counted insert (reorgs roll the count row back
    // as versioned state, they don't decrement), so underflow can only mean a
    // framework bug. Trap loudly and deterministically rather than clamp and let a
    // wrong count drive wrong decisions — surfacing corruption, not masking it.
    let next = if up {
        current + 1
    } else {
        current
            .checked_sub(1)
            .expect("Map bucket count underflow — framework bug")
    };
    ctx.__set_u64(bucket, next);
}

// The write TARGET (`S2`) is decoupled from the map's phantom context
// parameter (`S1`): a `Map` field is declared with the contract-local alias
// (fixing `S1`), but the containing struct's `Store` derive is generic over
// the handle it writes through.
impl<K, V, S1, S2> Store<S2> for crate::StorageMap<K, V, S1>
where
    K: KeyElement + Clone,
    V: Store<S2> + Clone + Indexed,
    S2: WriteStorage + ReadStorage + ?Sized,
{
    /// Wholesale write: persist every entry's value, plus its index rows when the
    /// value type declares indexes, so a map populated before `init` (at the root
    /// or any nested level) lands index-consistent. The index root is the
    /// `<primary>#idx` sibling, derived from `base_path` the same way the field
    /// model builds it. An upsert from empty (adds rows; per-key updates that must
    /// diff go through the field model's `set`). For a non-indexed value
    /// `HAS_INDEXES` is `false`, so the index block const-folds out and this is the
    /// plain entry write.
    fn __set(ctx: &Rc<S2>, base_path: KeyPath, value: crate::StorageMap<K, V, S1>) {
        for (k, v) in value.entries.into_iter() {
            if V::HAS_INDEXES
                && let Some(index_root) = base_path.interned_index_sibling()
            {
                apply_index_diff(ctx, &index_root, &k.encode(), &[], &v.index_entries());
            }
            ctx.__set(base_path.push_element(&k), v);
        }
    }
}

